#!/usr/bin/env node
// Builds hosted/seed/seed.sql from the profile JSON files in this directory.
// Usage: node hosted/seed/build-seed.mjs
// Then:  npx wrangler d1 execute personal-paper --local  --file hosted/seed/seed.sql
//        npx wrangler d1 execute personal-paper --remote --file hosted/seed/seed.sql
//
// Idempotent: re-running inserts a new version only if the definition changed.

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;

const files = readdirSync(here).filter((f) => f.endsWith(".json"));
let sql = "-- Generated by build-seed.mjs; do not edit by hand.\n";

for (const file of files) {
  const def = JSON.parse(readFileSync(join(here, file), "utf8"));
  const { id, name, visibility = "public", maintainer = null, description } = def;
  const definition = JSON.stringify(def);

  sql += `
-- ${id}
INSERT INTO profiles (id, name, visibility, maintainer, description, current_version)
VALUES (${q(id)}, ${q(name)}, ${q(visibility)}, ${maintainer ? q(maintainer) : "NULL"}, ${q(description)}, 0)
ON CONFLICT(id) DO UPDATE SET
  name = excluded.name, visibility = excluded.visibility, maintainer = excluded.maintainer,
  description = excluded.description, updated_at = strftime('%Y-%m-%dT%H:%M:%fZ', 'now');

INSERT INTO profile_versions (profile_id, version, definition, note)
SELECT ${q(id)},
       COALESCE((SELECT MAX(version) FROM profile_versions WHERE profile_id = ${q(id)}), 0) + 1,
       ${q(definition)}, 'seed'
WHERE NOT EXISTS (
  SELECT 1 FROM profile_versions pv
  WHERE pv.profile_id = ${q(id)}
    AND pv.version = (SELECT MAX(version) FROM profile_versions WHERE profile_id = ${q(id)})
    AND pv.definition = ${q(definition)}
);

UPDATE profiles SET current_version = (SELECT MAX(version) FROM profile_versions WHERE profile_id = ${q(id)})
WHERE id = ${q(id)};
`;
}

writeFileSync(join(here, "seed.sql"), sql);
console.log(`wrote seed.sql for ${files.length} profile(s): ${files.join(", ")}`);
