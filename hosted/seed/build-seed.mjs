#!/usr/bin/env node
// Builds hosted/seed/seed.sql from the topic definitions in hosted/topics/.
// Usage: node hosted/seed/build-seed.mjs
// Then:  npx wrangler d1 execute personal-paper --local  --file hosted/seed/seed.sql
//        npx wrangler d1 execute personal-paper --remote --file hosted/seed/seed.sql
//
// Idempotent: re-running inserts a new version only if the definition changed.

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const topicsDir = join(here, "..", "topics");
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;

const files = readdirSync(topicsDir).filter((f) => f.endsWith(".json")).sort();
let sql = "-- Generated by build-seed.mjs; do not edit by hand.\n";

for (const file of files) {
  const def = JSON.parse(readFileSync(join(topicsDir, file), "utf8"));
  const { id, name, visibility = "public", maintainer = null, description } = def;
  const definition = JSON.stringify(def);

  sql += `
-- ${id}
INSERT INTO topics (id, name, visibility, maintainer, description, current_version)
VALUES (${q(id)}, ${q(name)}, ${q(visibility)}, ${maintainer ? q(maintainer) : "NULL"}, ${q(description)}, 0)
ON CONFLICT(id) DO UPDATE SET
  name = excluded.name, visibility = excluded.visibility, maintainer = excluded.maintainer,
  description = excluded.description, updated_at = strftime('%Y-%m-%dT%H:%M:%fZ', 'now');

INSERT INTO topic_versions (topic_id, version, definition, note)
SELECT ${q(id)},
       COALESCE((SELECT MAX(version) FROM topic_versions WHERE topic_id = ${q(id)}), 0) + 1,
       ${q(definition)}, 'seed'
WHERE NOT EXISTS (
  SELECT 1 FROM topic_versions pv
  WHERE pv.topic_id = ${q(id)}
    AND pv.version = (SELECT MAX(version) FROM topic_versions WHERE topic_id = ${q(id)})
    AND pv.definition = ${q(definition)}
);

UPDATE topics SET current_version = (SELECT MAX(version) FROM topic_versions WHERE topic_id = ${q(id)})
WHERE id = ${q(id)};
`;
}

writeFileSync(join(here, "seed.sql"), sql);
console.log(`wrote seed.sql for ${files.length} topic(s): ${files.join(", ")}`);
